// ACA-US-12.1: builds the go/no-go review pack from docs/delivery/r1-evidence.json. The pack never reports a story as
// accepted without kept evidence and an owner acceptance reference, applies rule B3, and records no decision.
// Usage: node scripts/go-no-go-pack.mjs [--date YYYY-MM-DD]   → docs/delivery/go-no-go-pack.md
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const data = JSON.parse(readFileSync(join(root, 'docs/delivery/r1-evidence.json'), 'utf8'));
const date =
  (process.argv.indexOf('--date') > 0 ? process.argv[process.argv.indexOf('--date') + 1] : null) ??
  'not set (owner decision)';
const accepted = (s) =>
  s.accepted === true &&
  !!s.acceptanceRef &&
  s.evidence.length > 0 &&
  s.evidence.every((e) => existsSync(join(root, e)));
const lines = [
  `# Go/no-go review pack: ${data.release}`,
  '',
  `Generated by \`node scripts/go-no-go-pack.mjs\` on ${new Date().toISOString().slice(0, 10)}. Go/no-go date: ${date}.`,
  '',
  'This pack records no decision. Nakul Jain decides **go**, **go without teacher mode**, or **no-go**; the decision is recorded as the owner decision `golive.decision` and in Linear, linked to the roadmap.',
  '',
];
const byEpic = new Map();
for (const s of data.stories) byEpic.set(s.epic, [...(byEpic.get(s.epic) ?? []), s]);
lines.push(
  '## Status by epic',
  '',
  '| Epic | Stories | Accepted (with evidence) | Waiting on the owner |',
  '| --- | --- | --- | --- |',
);
for (const [e, ss] of byEpic)
  lines.push(
    `| ACA-${e} | ${ss.length} | ${ss.filter(accepted).length} | ${ss.filter((s) => s.ownerPrerequisites).length} |`,
  );
const textileReady = data.stories
  .filter((s) => data.textileLoopEpics.includes('ACA-' + s.epic))
  .every(accepted);
lines.push(
  '',
  '## Rule B3',
  '',
  textileReady
    ? 'Every textile-loop story (E2, E3, E4, E7) is accepted with evidence: teacher mode may be considered for R1.'
    : '**Not every textile-loop story (E2, E3, E4, E7) is accepted with evidence, so under rule B3 teacher and student modes move to the next release.** The options in this review are therefore "go without teacher mode" or "no-go".',
  '',
);
lines.push(
  '## Stories',
  '',
  '| Story | Code | Accepted | Evidence kept | Waiting on |',
  '| --- | --- | --- | --- | --- |',
);
for (const s of data.stories) {
  const missing = s.evidence.filter((e) => !existsSync(join(root, e)));
  lines.push(
    `| ${s.id} | ${s.code} | ${accepted(s) ? 'yes (' + s.acceptanceRef + ')' : 'no'} | ${missing.length ? 'MISSING: ' + missing.join(', ') : s.evidence.map((e) => '`' + e + '`').join(', ')} | ${s.ownerPrerequisites || '–'} |`,
  );
}
lines.push(
  '',
  '## Open risks',
  '',
  ...data.openRisks.map((r) => `- ${r}`),
  '',
  'Security findings: `docs/security/findings.md`. Accessibility: `docs/accessibility/statement.md`.',
  '',
);
writeFileSync(join(root, 'docs/delivery/go-no-go-pack.md'), lines.join('\n'));
console.log(
  JSON.stringify({
    stories: data.stories.length,
    accepted: data.stories.filter(accepted).length,
    textileReady,
  }),
);
