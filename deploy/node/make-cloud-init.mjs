#!/usr/bin/env node
// Print the cloud-init user-data that provisions a fresh Ubuntu 24.04 droplet as the Academy Node host, with no
// access to the repository: every file of this kit is embedded, so pasting the output into DigitalOcean's
// "User data" box at creation time is the whole provisioning step (ADR-0001, docs/operations/cutover-plan.md).
//
//   node deploy/node/make-cloud-init.mjs > /tmp/academy-user-data.yml
//
// What first boot does: installs Node 22, Caddy, Litestream, sqlite3 and ufw; creates the academy and deploy users;
// gives the deploy user the SSH key(s) DigitalOcean installed for root (the key chosen in the create form); installs
// this kit under /srv/academy/bin and /etc; generates the local secrets (auth, jobs, inbound) on the box and writes
// /etc/academy/academy.env; enables the services and the firewall. Provider keys (Resend, Anthropic, Spaces) are not
// in here: the GitHub deploy job carries them from the production environment secrets through set-secret.sh.
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const read = (f) => readFileSync(join(here, f), 'utf8');
const indent = (s, n) =>
  s
    .split('\n')
    .map((l) => (l.length ? ' '.repeat(n) + l : ''))
    .join('\n');
const file = (path, src, mode) =>
  `  - path: ${path}\n    permissions: '${mode}'\n    owner: root:root\n    content: |\n${indent(src.replace(/\s+$/, ''), 6)}\n`;

const AI_MODEL = process.env.ACADEMY_AI_MODEL ?? 'claude-sonnet-5-5';

const provisionRest = `#!/usr/bin/env bash
# Second half of provisioning, run once by cloud-init after the files above are in place.
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive
LITESTREAM_VERSION=0.3.13
curl -fsSL https://deb.nodesource.com/setup_22.x | bash - && apt-get -y install nodejs
curl -1sLf https://dl.cloudsmith.io/public/caddy/stable/gpg.key | gpg --dearmor -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
curl -1sLf https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt > /etc/apt/sources.list.d/caddy-stable.list
apt-get update && apt-get -y install caddy
curl -fsSL -o /tmp/litestream.deb "https://github.com/benbjohnson/litestream/releases/download/v\${LITESTREAM_VERSION}/litestream-v\${LITESTREAM_VERSION}-linux-amd64.deb"
dpkg -i /tmp/litestream.deb && rm -f /tmp/litestream.deb
install -m 644 /srv/academy/etc/Caddyfile /etc/caddy/Caddyfile
install -m 644 /srv/academy/etc/litestream.yml /etc/litestream.yml
# Users and folders (the users exist already; cloud-init created them)
mkdir -p /srv/academy/releases /srv/academy/snapshots /srv/academy/bin /var/lib/academy/files /etc/academy
chown -R academy:academy /var/lib/academy && chmod 700 /var/lib/academy
chown -R deploy:academy /srv/academy && chmod 750 /srv/academy
chmod 700 /etc/academy
# The deploy user gets the SSH key(s) DigitalOcean installed for root at creation.
install -d -m 700 -o deploy -g deploy /home/deploy/.ssh
if [ -s /root/.ssh/authorized_keys ]; then install -m 600 -o deploy -g deploy /root/.ssh/authorized_keys /home/deploy/.ssh/authorized_keys; fi
# Local secrets are generated here and never leave the box.
if [ ! -f /etc/academy/academy.env ]; then
  umask 077
  {
    echo 'ACADEMY_ENVIRONMENT=production'
    echo 'ACADEMY_PUBLIC_ORIGIN=https://academy.aplyd.org'
    echo 'ACADEMY_DATABASE_PATH=/var/lib/academy/academy.sqlite'
    echo 'ACADEMY_FILES_PATH=/var/lib/academy/files'
    echo "ACADEMY_AUTH_SECRET=$(openssl rand -base64 48 | tr -d '\\n')"
    echo "ACADEMY_JOBS_SECRET=$(openssl rand -base64 48 | tr -d '\\n')"
    echo "ACADEMY_INBOUND_SECRET=$(openssl rand -base64 48 | tr -d '\\n')"
    echo 'ACADEMY_MAIL_TRANSPORT=resend'
    echo 'ACADEMY_MAIL_FROM=Aplyd Academy <no-reply@aplyd.org>'
    echo 'ACADEMY_AI_PROVIDER=anthropic'
    echo 'ACADEMY_AI_MODEL=${AI_MODEL}'
  } > /etc/academy/academy.env
  touch /etc/academy/litestream.env && chmod 600 /etc/academy/litestream.env
fi
mkdir -p /etc/systemd/system/litestream.service.d
printf '[Service]\\nEnvironmentFile=/etc/academy/litestream.env\\n' > /etc/systemd/system/litestream.service.d/env.conf
systemctl daemon-reload && systemctl enable academy caddy academy-jobs.timer && systemctl restart caddy
ufw default deny incoming && ufw allow OpenSSH && ufw allow 80/tcp && ufw allow 443/tcp && ufw --force enable
echo "academy-blr1 provisioned $(date -u +%FT%TZ)" > /var/lib/academy-provisioned && chmod 644 /var/lib/academy-provisioned
`;

const sudoers = `deploy ALL=(root) NOPASSWD: /usr/bin/systemctl restart academy
deploy ALL=(root) NOPASSWD: /srv/academy/bin/academy-admin.sh *
deploy ALL=(root) NOPASSWD: /srv/academy/bin/set-secret.sh *
`;

let out = `#cloud-config
# Aplyd Academy Node host (ADR-0001 Option A). Generated by deploy/node/make-cloud-init.mjs; do not edit by hand.
hostname: academy-blr1
manage_etc_hosts: true
package_update: true
package_upgrade: true
packages:
  - curl
  - ca-certificates
  - gnupg
  - debian-keyring
  - debian-archive-keyring
  - apt-transport-https
  - sqlite3
  - ufw
  - unattended-upgrades
users:
  - default
  - name: deploy
    shell: /bin/bash
    lock_passwd: true
  - name: academy
    system: true
    shell: /usr/sbin/nologin
    homedir: /srv/academy
    no_create_home: true
    lock_passwd: true
write_files:
`;
out += file('/srv/academy/bin/run.sh', read('run.sh'), '0755');
out += file('/srv/academy/bin/release.sh', read('release.sh'), '0755');
out += file('/srv/academy/bin/restore-drill.sh', read('restore-drill.sh'), '0755');
out += file('/srv/academy/bin/jobs.sh', read('jobs.sh'), '0755');
out += file('/srv/academy/bin/academy-admin.sh', read('academy-admin.sh'), '0755');
out += file('/srv/academy/bin/set-secret.sh', read('set-secret.sh'), '0755');
out += file('/etc/systemd/system/academy.service', read('academy.service'), '0644');
out += file('/etc/systemd/system/academy-jobs.service', read('academy-jobs.service'), '0644');
out += file('/etc/systemd/system/academy-jobs.timer', read('academy-jobs.timer'), '0644');
// Caddy and Litestream ship their own copies of these two files; ours are staged and installed after the packages.
out += file('/srv/academy/etc/Caddyfile', read('Caddyfile'), '0644');
out += file('/srv/academy/etc/litestream.yml', read('litestream.yml'), '0644');
out += file('/etc/sudoers.d/academy-deploy', sudoers, '0440');
out += file('/root/provision-rest.sh', provisionRest, '0700');
out += `runcmd:
  - [bash, /root/provision-rest.sh]
final_message: "Aplyd Academy host ready after $UPTIME seconds; first release comes from the GitHub deploy job."
`;
process.stdout.write(out);
